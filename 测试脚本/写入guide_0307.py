def fill_guide(input_path: str, output_path: str):
    df = pd.read_excel(input_path, sheet_name='Sheet1', engine='openpyxl')

    if "guide" not in df.columns:
        df["guide"] = ""
    df["guide"] = df["guide"].astype(object)

    hit, miss = 0, 0
    for index, row in df.iterrows():
        cid = str(row["context_id"])
        if cid in GUIDE_MAP:
            df.at[index, "guide"] = GUIDE_MAP[cid]
            hit += 1
        else:
            miss += 1
            print(f"未找到 guide：context_id={cid}")

    df.to_excel(output_path, sheet_name='Sheet1', index=False)
    print(f"完成：写入 {hit} 条 guide，{miss} 条未匹配")


